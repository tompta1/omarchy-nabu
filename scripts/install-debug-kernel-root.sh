#!/bin/bash
set -euo pipefail
if [[ ${_NABU_BUILD_SCRIPT_LOADED:-} != "$0" ]]; then
  export _NABU_BUILD_SCRIPT_LOADED="$0"
  exec bash -c "$(cat -- "$0")" "$0" "$@"
fi
unset _NABU_BUILD_SCRIPT_LOADED
[[ -f /.omarchy-nabu-build-root ]] || exit 1
input=$(python3 /build/scripts/nabu_paths.py kernel)
output=$(python3 /build/scripts/nabu_paths.py output)
mkdir -p "$output/kernel-package"
slot=$(python3 /build/scripts/nabu_kernel.py --field slot)
package=linux-nabu-$slot
[[ $slot != local || ${NABU_BOOT_PROFILE:-legacy} == existing-uboot ]] || {
  echo 'Normal candidates require the maintained existing-U-Boot image layout.' >&2; exit 1;
}
uki_dir=/boot/efi/EFI/arch
if [[ ${NABU_BOOT_PROFILE:-legacy} == existing-uboot ]]; then uki_dir=/boot/EFI/arch; fi
if [[ ! -s $uki_dir/arch-linux-nabu-stock.efi ]]; then
  cp "$uki_dir/arch-linux-nabu.efi" "$uki_dir/arch-linux-nabu-stock.efi"
fi
cd "$input"
sha256sum -c SHA256SUMS
cd /
# Match upstream's partition/root arguments, with the extra debug arguments
# kept out of the stock kernel's command line.
python3 /build/scripts/nabu_kernel.py --cmdline-root /etc/cmdline.d/root.conf > "/etc/kernel/cmdline-nabu-$slot"
if ! id kernelbuild >/dev/null 2>&1; then
  useradd --system --user-group --create-home --shell /bin/bash kernelbuild
fi
work=$(mktemp -d /tmp/nabu-kernel-package.XXXXXX)
trap 'rm -rf "$work"; userdel -r kernelbuild 2>/dev/null || true' EXIT
cp /build/kernel/PKGBUILD "$work/"
# CI outputs may be behind mode-0700 directories. The unprivileged package
# builder reads a private, owned copy, never the outer runner's artifact path.
mkdir "$work/input"
for artifact in kernelrelease Image Image.gz sm8150-xiaomi-nabu.dtb modules.tar config; do
  cp "$input/$artifact" "$work/input/"
done
if grep -qx CONFIG_EFI_ZBOOT=y "$input/config"; then
  cp "$input/vmlinuz.efi" "$work/input/"
fi
chown -R kernelbuild:kernelbuild "$work"
# shellcheck disable=SC2016 # $1 belongs to the child shell, passed as an argument.
runuser -u kernelbuild -- /usr/bin/bash -ec '
  cd "$1"
  export NABU_KERNEL_INPUT="$PWD/input" NABU_KERNEL_UKI_DIR="$2" NABU_KERNEL_SLOT="$3" NABU_BOOT_MANAGER="$4"
  exec /usr/bin/makepkg --nodeps --noconfirm
' bash "$work" "$uki_dir" "$slot" "${NABU_BOOT_MANAGER:-grub}"
cp "$work"/"$package"-*.pkg.tar.* "$output/kernel-package/"
# Build the selected UKI once below. Automatic hooks otherwise rebuild every
# kernel here, including the stock UKI just generated by layout provisioning.
mkdir "$work/hooks"
shopt -s nullglob
python3 /build/scripts/nabu_package_hooks.py --output "$work/hooks" "$work"/"$package"-*.pkg.tar.*
env OMARCHY_UPDATE_PACMAN=1 pacman --hookdir "$work/hooks" -U --noconfirm "$work"/"$package"-*.pkg.tar.*
depmod -a "$(cat "$input/kernelrelease")"
/usr/bin/mkinitcpio -p "$package" 2>&1 | tee "$output/initramfs-$slot.log"
test -s "$uki_dir/arch-linux-nabu.efi"
test -s "$uki_dir/arch-linux-nabu-$slot.efi"
if [[ ${NABU_BOOT_MANAGER:-grub} == limine ]]; then
  python3 - "$uki_dir/arch-linux-nabu-$slot.efi" "$input/config" <<'PY_CHECK'
import sys
sys.path.insert(0, '/build/scripts')
from nabu_limine import verify_snapshot_initramfs
release = verify_snapshot_initramfs(sys.argv[1], sys.argv[2])
print('Verified snapshot initramfs payload for '+release)
PY_CHECK
  # Limine rebuilds every installed kernel on generic initramfs updates. The
  # replacement provides linux-nabu; omit the old stock package only in
  # this isolated final-image root, after the selected snapshot UKI passes.
  installed=$(pacman -Qq)
  retired=()
  for stock_package in linux-nabu linux-nabu-headers; do
    if grep -Fxq -- "$stock_package" <<< "$installed"; then
      retired+=("$stock_package")
    fi
  done
  if (( ${#retired[@]} )); then
    env OMARCHY_UPDATE_PACMAN=1 pacman --hookdir "$work/hooks" -R --noscriptlet --noconfirm "${retired[@]}"
  fi
fi
if [[ $slot == local ]] && pacman -Q linux-nabu-debug >/dev/null 2>&1; then
  # This is a marked isolated image root, never the running tablet. A normal
  # image carries the selected local kernel and stock fallback, not the old
  # diagnostic package/UKI inherited from its prepared base.
  env OMARCHY_UPDATE_PACMAN=1 pacman --hookdir "$work/hooks" -R --noconfirm linux-nabu-debug
  rm -f "$uki_dir/arch-linux-nabu-debug.efi" /etc/kernel/cmdline-nabu-debug
fi
# Nabu's generic rebuild hook also saves an old UKI. Keep the independently
# named stock entry and remove only a byte-identical duplicate to fit the ESP.
if cmp -s "$uki_dir/arch-linux-nabu-old.efi" "$uki_dir/arch-linux-nabu-stock.efi"; then
  rm "$uki_dir/arch-linux-nabu-old.efi"
fi
if [[ ${NABU_BOOT_PROFILE:-legacy} != existing-uboot ]] && ! grep -q '^# Omarchy Nabu debug entries' /boot/efi/EFI/BOOT/refind.conf; then
  cat >> /boot/efi/EFI/BOOT/refind.conf <<'EOF'

# Omarchy Nabu debug entries
default_selection "Omarchy Nabu debug"
menuentry "Omarchy Nabu debug" {
  loader /EFI/arch/arch-linux-nabu-debug.efi
}
menuentry "Omarchy Nabu stock fallback" {
  loader /EFI/arch/arch-linux-nabu-stock.efi
}
EOF
fi
install -Dm755 /build/scripts/omarchy-nabu-debug-collect /usr/local/bin/omarchy-nabu-debug-collect
mkdir -p /etc/systemd/journald.conf.d
printf '[Journal]\nStorage=persistent\nSystemMaxUse=256M\n' > /etc/systemd/journald.conf.d/90-nabu-logging.conf
rm -f /etc/systemd/journald.conf.d/90-nabu-debug.conf
mkdir -p /var/log/journal
if [[ ${NABU_BOOT_PROFILE:-legacy} != existing-uboot ]]; then tar czf /opt/nabu/efi.tgz -C /boot/efi .; fi
pacman -Q > "$output/packages.lock"
